//go:build linux

package metrics

import (
	"reflect"
	"strings"
	"testing"
)

func TestDefaultIPv4RoutesUseMetricAndRejectInvalidRoutes(t *testing.T) {
	routes := `Iface Destination Gateway Flags RefCnt Use Metric Mask MTU Window IRTT
eth2 00000000 0100030A 0003 0 0 200 00000000 0 0 0
eth1 00000000 0100030A 0003 0 0 100 00000000 0 0 0
br0 000012AC 00000000 0001 0 0 0 0000FFFF 0 0 0
eth3 00000000 00000000 0201 0 0 0 00000000 0 0 0
eth4 00000000 00000000 0000 0 0 0 00000000 0 0 0
eth5 00000000 00000000 0001 0 0 invalid 00000000 0 0 0
malformed
`
	got := routeInterfaces(strings.NewReader(routes), false)
	if !reflect.DeepEqual(got, []string{"eth1", "eth2"}) {
		t.Fatal(got)
	}
}
